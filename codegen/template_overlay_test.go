func TestOverlayOrderingAndPrecedence(t *testing.T) {
	// First overlay changes expr.go.gotmpl and document.go.gotmpl
	ov1 := codegen.OverlayTxtar([]byte(`-- expr.go.gotmpl --
// Code generated by gogenconf. DO NOT EDIT.
package {{.Package}}
// Layer1Expr
type Expr interface{}
-- document.go.gotmpl --
// Code generated by gogenconf. DO NOT EDIT.
package {{.Package}}
// Layer1Doc
type Document struct{}
`))

	// Second overlay replaces expr.go.gotmpl with Layer2Expr, leaving document.go.gotmpl as Layer1Doc
	ov2 := codegen.OverlayFile("expr.go.gotmpl", `// Code generated by gogenconf. DO NOT EDIT.
package {{.Package}}
// Layer2Expr
type Expr interface{}
`)

	opts := codegen.RuntimeOptions{
		Package:      "orderconf",
		Capabilities: []codegen.Capability{codegen.CapabilityDocument, codegen.CapabilityExpr},
		Overlays:     []codegen.Overlay{ov1, ov2},
	}

	files, err := codegen.GenerateRuntime(opts)
	if err != nil {
		t.Fatalf("GenerateRuntime failed: %v", err)
	}

	for _, f := range files {
		if strings.HasSuffix(f.Name, "expr_generated.go") {
			if !bytes.Contains(f.Content, []byte("Layer2Expr")) {
				t.Errorf("later overlay should win: %s", string(f.Content))
			}
			if bytes.Contains(f.Content, []byte("Layer1Expr")) {
				t.Errorf("earlier overlay should be replaced")
			}
		}
		if strings.HasSuffix(f.Name, "document_generated.go") {
			if !bytes.Contains(f.Content, []byte("Layer1Doc")) {
				t.Errorf("unrelated template from earlier layer should be preserved: %s", string(f.Content))
			}
		}
	}
}

