func TestBuiltinTemplateLayout(t *testing.T) {
	layout := codegen.BuiltinTemplateLayout()
	if len(layout) < 4 {
		t.Fatalf("expected at least 4 built-in templates, got %d", len(layout))
	}

	found := make(map[string]bool)
	for _, info := range layout {
		found[info.Name] = true
		if info.TargetFile == "" {
			t.Errorf("template %s has empty target file", info.Name)
		}
		if info.Description == "" {
			t.Errorf("template %s has empty description", info.Name)
		}
	}

	for _, req := range []string{"document.go.gotmpl", "expr.go.gotmpl", "format.go.gotmpl", "parse.go.gotmpl"} {
		if !found[req] {
			t.Errorf("missing expected built-in template %s", req)
		}
	}
}

func TestExportTemplatesDirectory(t *testing.T) {
	tmpDir := t.TempDir()
	outDir := filepath.Join(tmpDir, "exported")

	if err := codegen.ExportTemplates(outDir); err != nil {
		t.Fatalf("ExportTemplates failed: %v", err)
	}

	entries, err := os.ReadDir(outDir)
	if err != nil {
		t.Fatalf("ReadDir failed: %v", err)
	}
	if len(entries) < 4 {
		t.Fatalf("expected at least 4 files, got %d", len(entries))
	}

	for _, e := range entries {
		data, err := os.ReadFile(filepath.Join(outDir, e.Name()))
		if err != nil {
			t.Fatalf("read exported %s: %v", e.Name(), err)
		}
		if len(data) == 0 {
			t.Errorf("exported template %s is empty", e.Name())
		}
	}
}

