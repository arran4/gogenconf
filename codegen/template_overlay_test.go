func TestOverlayDeterministicGeneration(t *testing.T) {
	opts := codegen.RuntimeOptions{
		Package: "detpkg",
		Overlays: []codegen.Overlay{
			codegen.OverlayFile("expr.go.gotmpl", `// Code generated by gogenconf. DO NOT EDIT.
package {{.Package}}
type Expr struct{ Val string }
`),
		},
	}

	run1, err := codegen.GenerateRuntime(opts)
	if err != nil {
		t.Fatalf("run1 failed: %v", err)
	}
	run2, err := codegen.GenerateRuntime(opts)
	if err != nil {
		t.Fatalf("run2 failed: %v", err)
	}

	if len(run1) != len(run2) {
		t.Fatalf("mismatched file count: %d vs %d", len(run1), len(run2))
	}
	for i := range run1 {
		if run1[i].Name != run2[i].Name {
			t.Errorf("file name mismatch at %d: %s vs %s", i, run1[i].Name, run2[i].Name)
		}
		if !bytes.Equal(run1[i].Content, run2[i].Content) {
			t.Errorf("content mismatch at %s", run1[i].Name)
		}
	}
}

