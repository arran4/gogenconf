func TestOverlayIsolatedConsumerCompilation(t *testing.T) {
	// Custom template adds helper method to Document
	customDocTmpl := `// Code generated by gogenconf. DO NOT EDIT.

package {{.Package}}

// Origin and Span are part of the generated document/expr template contract.
// A full document-template replacement must provide them when the selected
// expression template carries source provenance.
type Origin uint8

const (
	OriginAuthored Origin = iota
	OriginDefaulted
	OriginEnriched
	OriginMigrated
)

type Span struct {
	Source string
	Line   int
	Column int
	Offset int
}

type Document struct {
	Items []string
}

func (d *Document) CustomHelper() int {
	return len(d.Items)
}
`
	opts := codegen.RuntimeOptions{
		Package: "isolatedconf",
		Capabilities: []codegen.Capability{
			codegen.CapabilityDocument,
		},
		Overlays: []codegen.Overlay{
			codegen.OverlayFile("document.go.gotmpl", customDocTmpl),
		},
	}

	files, err := codegen.GenerateRuntime(opts)
	if err != nil {
		t.Fatalf("GenerateRuntime failed: %v", err)
	}

	tmpDir := t.TempDir()
	modContent := `module isolated.test/consumer

go 1.24
`
	if err := os.WriteFile(filepath.Join(tmpDir, "go.mod"), []byte(modContent), 0644); err != nil {
		t.Fatalf("write go.mod: %v", err)
	}

	confDir := filepath.Join(tmpDir, "isolatedconf")
	if err := os.MkdirAll(confDir, 0755); err != nil {
		t.Fatalf("mkdir confDir: %v", err)
	}

	for _, f := range files {
		if err := os.WriteFile(filepath.Join(confDir, f.Name), f.Content, 0644); err != nil {
			t.Fatalf("write %s: %v", f.Name, err)
		}
	}

	// Write consumer test exercising custom template helper
	testCode := `package consumer_test

import (
	"testing"
	"isolated.test/consumer/isolatedconf"
)

func TestCustomConsumer(t *testing.T) {
	doc := isolatedconf.Document{Items: []string{"a", "b"}}
	if doc.CustomHelper() != 2 {
		t.Fatalf("expected 2, got %d", doc.CustomHelper())
	}
}
`
	if err := os.WriteFile(filepath.Join(tmpDir, "consumer_test.go"), []byte(testCode), 0644); err != nil {
		t.Fatalf("write consumer_test.go: %v", err)
	}

	// 1. Run go test
	cmd := exec.Command("go", "test", "./...")
	cmd.Dir = tmpDir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go test failed: %v\n%s", err, string(out))
	}

	// 2. Verify zero runtime dependency on github.com/arran4/gogenconf
	depsCmd := exec.Command("go", "list", "-deps", "./isolatedconf")
	depsCmd.Dir = tmpDir
	depsOut, err := depsCmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go list -deps failed: %v\n%s", err, string(depsOut))
	}
	if strings.Contains(string(depsOut), "github.com/arran4/gogenconf") {
		t.Fatalf("generated code depends on github.com/arran4/gogenconf:\n%s", string(depsOut))
	}
}
