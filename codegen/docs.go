package codegen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	m "github.com/arran4/gogenconf"
)

// DocOptions configures Markdown configuration reference documentation generation.
type DocOptions struct {
	AppName string // Application name, e.g. "downloadsd"
	Title   string // Document title
}

// ManOptions configures Unix man-page generation (section 5 for file formats).
type ManOptions struct {
	AppName string // Application name, e.g. "downloadsd"
	Section int    // Man section, default 5
	Manual  string // Manual name, default "File Formats Manual"
	Source  string // Document source
}

// GenerateMarkdown generates a comprehensive Markdown reference document from schema metadata.
func GenerateMarkdown(s *m.Schema, opts DocOptions) ([]byte, error) {
	if s == nil {
		return nil, fmt.Errorf("nil schema")
	}

	app := opts.AppName
	if app == "" {
		if s.Identity != "" {
			app = strings.TrimSuffix(s.Identity, "-schema")
		} else {
			app = "Application"
		}
	}

	title := opts.Title
	if title == "" {
		title = fmt.Sprintf("%s Configuration Reference", app)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", title)
	fmt.Fprintf(&b, "Configuration specification version: **%d**\n\n", s.Version)

	if len(s.Sections) > 0 {
		fmt.Fprintf(&b, "## Contents\n\n")
		for _, sec := range s.Sections {
			fmt.Fprintf(&b, "- [%s](#%s)\n", sec.Name, strings.ToLower(sec.Name))
		}
		fmt.Fprintf(&b, "\n")
	}

	for _, sec := range s.Sections {
		repNote := ""
		if sec.Repeated {
			repNote = " *(repeated section)*"
		}
		fmt.Fprintf(&b, "## %s%s\n\n", sec.Name, repNote)

		for _, doc := range sec.Documentation {
			fmt.Fprintf(&b, "%s\n\n", doc)
		}

		if sec.Repeated && len(sec.ExampleNames) > 0 {
			fmt.Fprintf(&b, "Example instances: `%s`\n\n", strings.Join(sec.ExampleNames, "`, `"))
		}

		if len(sec.Fields) > 0 {
			fmt.Fprintf(&b, "| Field | Type | Default | Attributes | Description |\n")
			fmt.Fprintf(&b, "| --- | --- | --- | --- | --- |\n")

			for _, f := range sec.Fields {
				defStr := "-"
				if f.Default != nil {
					defStr = "`" + m.FormatExpr(f.Default) + "`"
				}

				var attrs []string
				if f.Required {
					attrs = append(attrs, "**Required**")
				}
				if f.Sensitive {
					attrs = append(attrs, "Sensitive")
				}
				if f.RuntimeOnly {
					attrs = append(attrs, "RuntimeOnly")
				}
				if f.InputOnly {
					attrs = append(attrs, "InputOnly")
				}
				if f.Deprecated {
					attrs = append(attrs, "Deprecated")
				}
				if f.Policy != "" {
					attrs = append(attrs, "Policy: "+string(f.Policy))
				}
				if f.Environment != "" {
					attrs = append(attrs, "Env: `"+f.Environment+"`")
				}

				attrStr := "-"
				if len(attrs) > 0 {
					attrStr = strings.Join(attrs, ", ")
				}

				docStr := strings.Join(f.Documentation, " ")
				if docStr == "" {
					docStr = "-"
				}

				fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n",
					f.Key, f.ResolvedGoType(), defStr, attrStr, docStr)
			}
			fmt.Fprintf(&b, "\n")

			// Check for examples
			hasExamples := false
			for _, f := range sec.Fields {
				if len(f.Examples) > 0 {
					hasExamples = true
					break
				}
			}

			if hasExamples {
				fmt.Fprintf(&b, "### %s Examples\n\n```text\nsection %s\n", sec.Name, sec.Name)
				for _, f := range sec.Fields {
					for _, ex := range f.Examples {
						if ex != nil {
							fmt.Fprintf(&b, "    %s %s\n", f.Key, m.FormatExpr(ex))
						}
					}
				}
				fmt.Fprintf(&b, "end\n```\n\n")
			}
		}
	}

	return []byte(b.String()), nil
}

// GenerateManPage generates a roff/troff section 5 man page from schema metadata.
func GenerateManPage(s *m.Schema, opts ManOptions) ([]byte, error) {
	if s == nil {
		return nil, fmt.Errorf("nil schema")
	}

	app := opts.AppName
	if app == "" {
		if s.Identity != "" {
			app = strings.TrimSuffix(s.Identity, "-schema")
		} else {
			app = "config"
		}
	}

	secNum := opts.Section
	if secNum == 0 {
		secNum = 5
	}

	manual := opts.Manual
	if manual == "" {
		manual = "File Formats Manual"
	}

	source := opts.Source
	if source == "" {
		source = app
	}

	var b strings.Builder
	fmt.Fprintf(&b, ".\\\" Generated by gogenconf. DO NOT EDIT.\n")
	fmt.Fprintf(&b, ".TH %s.%d %d \"\" %q %q\n", strings.ToUpper(app), secNum, secNum, source, manual)
	fmt.Fprintf(&b, ".SH NAME\n")
	fmt.Fprintf(&b, "%s.%d \\- %s configuration file\n", app, secNum, app)
	fmt.Fprintf(&b, ".SH SYNOPSIS\n")
	fmt.Fprintf(&b, ".B config for %s version %d\n", app, s.Version)
	fmt.Fprintf(&b, ".SH DESCRIPTION\n")
	fmt.Fprintf(&b, "%s is configured using a versioned declarative configuration file format.\n", app)
	fmt.Fprintf(&b, ".SH SECTIONS\n")

	for _, sec := range s.Sections {
		rep := ""
		if sec.Repeated {
			rep = " (repeated)"
		}
		fmt.Fprintf(&b, ".SS %s%s\n", sec.Name, rep)
		for _, doc := range sec.Documentation {
			fmt.Fprintf(&b, "%s\n.br\n", doc)
		}

		for _, f := range sec.Fields {
			attrs := []string{f.ResolvedGoType()}
			if f.Required {
				attrs = append(attrs, "required")
			}
			if f.Default != nil {
				attrs = append(attrs, "default: "+m.FormatExpr(f.Default))
			}
			if f.Sensitive {
				attrs = append(attrs, "sensitive")
			}
			if f.Environment != "" {
				attrs = append(attrs, "env: "+f.Environment)
			}

			fmt.Fprintf(&b, ".TP\n.B %s \\fR(%s)\\fR\n", f.Key, strings.Join(attrs, ", "))
			for _, doc := range f.Documentation {
				fmt.Fprintf(&b, "%s\n", doc)
			}
			for _, ex := range f.Examples {
				if ex != nil {
					fmt.Fprintf(&b, "Example: \\fI%s %s\\fR\n.br\n", f.Key, m.FormatExpr(ex))
				}
			}
		}
	}

	fmt.Fprintf(&b, ".SH SEE ALSO\n")
	fmt.Fprintf(&b, "gogenconf(1)\n")

	return []byte(b.String()), nil
}

// GenerateSampleDoc returns the canonical sample configuration document bytes.
func GenerateSampleDoc(s *m.Schema) []byte {
	if s == nil {
		return nil
	}
	sampleDoc := s.Sample()
	return []byte(m.Format(sampleDoc))
}

// DocProjectOptions configures multi-artifact documentation generation and CI checking.
type DocProjectOptions struct {
	SchemaFile   string
	Schema       *m.Schema
	OutputDir    string
	AppName      string
	EmitMarkdown bool
	MarkdownFile string
	EmitMan      bool
	ManFile      string
	EmitSample   bool
	SampleFile   string
	CheckOnly    bool
}

// DocPlan models planned documentation files before disk emission.
type DocPlan struct {
	OutputDir string
	Files     FileSet
}

// PlanDocs generates the multi-file documentation plan.
func PlanDocs(opts DocProjectOptions) (*DocPlan, error) {
	s := opts.Schema
	if s == nil {
		var err error
		s, err = LoadAndValidateSchema(opts.SchemaFile)
		if err != nil {
			return nil, err
		}
	}

	outDir := opts.OutputDir
	if outDir == "" {
		outDir = "."
	}

	app := opts.AppName
	if app == "" {
		if s.Identity != "" {
			app = strings.TrimSuffix(s.Identity, "-schema")
		} else {
			app = "config"
		}
	}

	var files FileSet

	if opts.EmitMarkdown {
		mdFile := opts.MarkdownFile
		if mdFile == "" {
			mdFile = app + ".md"
		}
		mdBytes, err := GenerateMarkdown(s, DocOptions{AppName: app})
		if err != nil {
			return nil, err
		}
		files = append(files, GeneratedFile{Name: mdFile, Content: mdBytes})
	}

	if opts.EmitMan {
		manFile := opts.ManFile
		if manFile == "" {
			manFile = app + ".5"
		}
		manBytes, err := GenerateManPage(s, ManOptions{AppName: app, Section: 5})
		if err != nil {
			return nil, err
		}
		files = append(files, GeneratedFile{Name: manFile, Content: manBytes})
	}

	if opts.EmitSample {
		sampleFile := opts.SampleFile
		if sampleFile == "" {
			sampleFile = "sample.conf"
		}
		files = append(files, GeneratedFile{Name: sampleFile, Content: GenerateSampleDoc(s)})
	}

	return &DocPlan{
		OutputDir: outDir,
		Files:     files,
	}, nil
}

// Execute applies the documentation plan according to the options.
func (p *DocPlan) Execute(opts DocProjectOptions) error {
	outDir := p.OutputDir
	if outDir == "" {
		outDir = "."
	}

	if opts.CheckOnly {
		for _, f := range p.Files {
			targetPath := filepath.Join(outDir, f.Name)
			diskContent, err := os.ReadFile(targetPath)
			if err != nil {
				return fmt.Errorf("missing documentation file %q: %w", f.Name, err)
			}
			if !bytes.Equal(diskContent, f.Content) {
				return fmt.Errorf("documentation file %q is stale / out of date", f.Name)
			}
		}
		return nil
	}

	return p.Files.WriteToDir(outDir)
}
