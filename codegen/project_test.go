package codegen_test

import (
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"

	m "github.com/arran4/gogenconf"
	"github.com/arran4/gogenconf/codegen"
)

const sampleSchema = `config for downloadsd-schema version 1

section service
    host string
    port int
    max_retries int
end

section storage
    path string
    temp_dir string
end
`

func TestPlanProjectFromSchemaString(t *testing.T) {
	schema, err := m.ParseSchemaNamed(strings.NewReader(sampleSchema), "test.conf")
	if err != nil {
		t.Fatalf("ParseSchemaNamed failed: %v", err)
	}

	plan, err := codegen.PlanProject(codegen.ProjectOptions{
		Schema:    schema,
		OutputDir: "pkg/downloadsd",
	})
	if err != nil {
		t.Fatalf("PlanProject failed: %v", err)
	}

	if plan.Package != "downloadsd" {
		t.Errorf("expected package downloadsd, got %q", plan.Package)
	}

	genFile := plan.Files.File("config_generated.go")
	if genFile == nil {
		t.Fatal("expected config_generated.go in plan.Files")
	}

	if !strings.Contains(string(genFile.Content), "// Code generated by gogenconf. DO NOT EDIT.") {
		t.Error("expected neutral DO NOT EDIT header")
	}

	// Verify valid Go code
	fset := token.NewFileSet()
	if _, err := parser.ParseFile(fset, "config_generated.go", genFile.Content, parser.AllErrors); err != nil {
		t.Fatalf("emitted source is invalid Go: %v\nSource:\n%s", err, string(genFile.Content))
	}
}

func TestProjectExecuteAtomicAndCheck(t *testing.T) {
	tmpDir := t.TempDir()
	schemaFile := filepath.Join(tmpDir, "schema.conf")
	if err := os.WriteFile(schemaFile, []byte(sampleSchema), 0644); err != nil {
		t.Fatal(err)
	}

	outDir := filepath.Join(tmpDir, "client")

	// 1. Initial generation
	opts := codegen.ProjectOptions{
		SchemaFile: schemaFile,
		OutputDir:  outDir,
		Package:    "client",
	}

	plan, err := codegen.PlanProject(opts)
	if err != nil {
		t.Fatalf("PlanProject failed: %v", err)
	}

	if err := plan.Execute(opts); err != nil {
		t.Fatalf("plan.Execute failed: %v", err)
	}

	targetFile := filepath.Join(outDir, "config_generated.go")
	content, err := os.ReadFile(targetFile)
	if err != nil {
		t.Fatalf("failed reading written file: %v", err)
	}
	if !strings.Contains(string(content), "package client") {
		t.Errorf("expected package client in content")
	}

	// 2. CheckOnly should succeed when matching
	opts.CheckOnly = true
	if err := plan.Execute(opts); err != nil {
		t.Fatalf("CheckOnly failed when files match: %v", err)
	}

	// 3. CheckOnly should fail when file on disk is modified
	if err := os.WriteFile(targetFile, []byte("// modified\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := plan.Execute(opts); err == nil {
		t.Fatal("expected CheckOnly to fail when disk file is stale, but got nil")
	}

	// 4. CheckOnly should fail when file on disk is missing
	_ = os.Remove(targetFile)
	if err := plan.Execute(opts); err == nil {
		t.Fatal("expected CheckOnly to fail when disk file is missing, but got nil")
	}
}

func TestProjectExecuteCleanMode(t *testing.T) {
	tmpDir := t.TempDir()
	schemaFile := filepath.Join(tmpDir, "schema.conf")
	if err := os.WriteFile(schemaFile, []byte(sampleSchema), 0644); err != nil {
		t.Fatal(err)
	}

	outDir := filepath.Join(tmpDir, "out")
	if err := os.MkdirAll(outDir, 0755); err != nil {
		t.Fatal(err)
	}

	// Create an obsolete generated file
	obsFile := filepath.Join(outDir, "old_feature_generated.go")
	obsContent := "// Code generated by gogenconf. DO NOT EDIT.\npackage out\n"
	if err := os.WriteFile(obsFile, []byte(obsContent), 0644); err != nil {
		t.Fatal(err)
	}

	// Create a user file
	userFile := filepath.Join(outDir, "user_code.go")
	userContent := "package out\n// Authored by user\n"
	if err := os.WriteFile(userFile, []byte(userContent), 0644); err != nil {
		t.Fatal(err)
	}

	opts := codegen.ProjectOptions{
		SchemaFile: schemaFile,
		OutputDir:  outDir,
		Clean:      true,
	}

	plan, err := codegen.PlanProject(opts)
	if err != nil {
		t.Fatal(err)
	}

	if len(plan.ObsoleteFiles) != 1 || plan.ObsoleteFiles[0] != "old_feature_generated.go" {
		t.Fatalf("expected old_feature_generated.go in ObsoleteFiles, got %v", plan.ObsoleteFiles)
	}

	if err := plan.Execute(opts); err != nil {
		t.Fatalf("plan.Execute failed: %v", err)
	}

	// Obsolete generated file should be removed
	if _, err := os.Stat(obsFile); !os.IsNotExist(err) {
		t.Errorf("expected obsolete file to be removed")
	}

	// User-authored file must be preserved
	if _, err := os.Stat(userFile); err != nil {
		t.Errorf("user-authored file was erroneously deleted: %v", err)
	}
}

func TestProjectEmitRuntimeAndSample(t *testing.T) {
	tmpDir := t.TempDir()
	schemaFile := filepath.Join(tmpDir, "schema.conf")
	if err := os.WriteFile(schemaFile, []byte(sampleSchema), 0644); err != nil {
		t.Fatal(err)
	}

	outDir := filepath.Join(tmpDir, "gen")

	opts := codegen.ProjectOptions{
		SchemaFile:  schemaFile,
		OutputDir:   outDir,
		EmitRuntime: true,
		EmitSample:  true,
		SampleFile:  "app.sample.conf",
	}

	plan, err := codegen.PlanProject(opts)
	if err != nil {
		t.Fatal(err)
	}

	expectedFiles := []string{
		"config_generated.go",
		"config_document_generated.go",
		"config_expr_generated.go",
		"config_format_generated.go",
		"config_parse_generated.go",
		"app.sample.conf",
	}

	for _, name := range expectedFiles {
		if f := plan.Files.File(name); f == nil {
			t.Errorf("missing planned file %s", name)
		}
	}

	if err := plan.Execute(opts); err != nil {
		t.Fatal(err)
	}

	for _, name := range expectedFiles {
		path := filepath.Join(outDir, name)
		if _, err := os.Stat(path); err != nil {
			t.Errorf("expected file %s to exist on disk: %v", name, err)
		}
	}

	summary := plan.Summary()
	if !strings.Contains(summary, "Generation Plan:") {
		t.Errorf("unexpected summary output: %s", summary)
	}

	jsonData, err := plan.JSON()
	if err != nil {
		t.Fatalf("plan.JSON failed: %v", err)
	}
	if !strings.Contains(string(jsonData), `"capabilities"`) {
		t.Errorf("unexpected json output: %s", string(jsonData))
	}
}
