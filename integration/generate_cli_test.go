package integration

import (
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"testing"

	"github.com/arran4/gogenconf/internal/cli"
)

const cliTestSchema = `config for downloadsd-schema version 1

section service
    host string
    port int
end

section database
    dsn string
    max_connections int
end
`

func TestGenerateCLICommandEndToEnd(t *testing.T) {
	tmpDir := t.TempDir()
	schemaPath := filepath.Join(tmpDir, "downloadsd-schema.conf")
	if err := os.WriteFile(schemaPath, []byte(cliTestSchema), 0644); err != nil {
		t.Fatal(err)
	}

	outDir := filepath.Join(tmpDir, "pkg", "config")

	// 1. Run cli.Generate programmatically
	err := cli.Generate(schemaPath, "", outDir, "config", false, false, true, true)
	if err != nil {
		t.Fatalf("cli.Generate failed: %v", err)
	}

	// Verify generated files exist
	expected := []string{
		"config_generated.go",
		"config_document_generated.go",
		"config_expr_generated.go",
		"config_format_generated.go",
		"config_parse_generated.go",
		"sample.conf",
	}

	for _, name := range expected {
		p := filepath.Join(outDir, name)
		if _, err := os.Stat(p); err != nil {
			t.Errorf("expected generated file %s to exist: %v", name, err)
		}
	}

	// 2. Test --check succeeds on unmodified tree
	err = cli.Generate(schemaPath, "", outDir, "config", true, false, true, true)
	if err != nil {
		t.Fatalf("cli.Generate --check failed on fresh output: %v", err)
	}

	// 3. Test --check fails when a file is modified
	cfgFile := filepath.Join(outDir, "config_generated.go")
	if err := os.WriteFile(cfgFile, []byte("// Code generated by gogenconf. DO NOT EDIT.\n// tampered\n"), 0644); err != nil {
		t.Fatal(err)
	}
	err = cli.Generate(schemaPath, "", outDir, "config", true, false, true, true)
	if err == nil {
		t.Fatal("expected cli.Generate --check to fail on tampered file, got nil")
	}

	// 4. Test --clean removes obsolete file
	obsFile := filepath.Join(outDir, "obsolete_generated.go")
	if err := os.WriteFile(obsFile, []byte("// Code generated by gogenconf. DO NOT EDIT.\n"), 0644); err != nil {
		t.Fatal(err)
	}
	userFile := filepath.Join(outDir, "user_notes.txt")
	if err := os.WriteFile(userFile, []byte("user notes"), 0644); err != nil {
		t.Fatal(err)
	}

	// Regenerate with clean = true
	err = cli.Generate(schemaPath, "", outDir, "config", false, true, true, true)
	if err != nil {
		t.Fatalf("cli.Generate with clean failed: %v", err)
	}

	if _, err := os.Stat(obsFile); !os.IsNotExist(err) {
		t.Errorf("expected obsolete generated file to be removed")
	}
	if _, err := os.Stat(userFile); err != nil {
		t.Errorf("user-owned file was deleted: %v", err)
	}

	// 5. Run actual gogenconf binary via exec
	cmdDir := t.TempDir()
	binSchema := filepath.Join(cmdDir, "schema.conf")
	if err := os.WriteFile(binSchema, []byte(cliTestSchema), 0644); err != nil {
		t.Fatal(err)
	}
	binOut := filepath.Join(cmdDir, "client")

	cmd := exec.Command("go", "run", "./cmd/gogenconf", "generate", "--schema", binSchema, "--out", binOut, "--pkg", "client")
	rootPath, _ := filepath.Abs("..")
	cmd.Dir = rootPath
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go run cmd/gogenconf generate failed: %v\nOutput:\n%s", err, string(out))
	}

	if _, err := os.Stat(filepath.Join(binOut, "config_generated.go")); err != nil {
		t.Fatalf("config_generated.go missing from binary invocation: %v", err)
	}

	// Test plan --json via binary
	planCmd := exec.Command("go", "run", "./cmd/gogenconf", "plan", "--schema", binSchema, "--json")
	planCmd.Dir = rootPath
	planOut, err := planCmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go run cmd/gogenconf plan --json failed: %v\nOutput:\n%s", err, string(planOut))
	}

	var planPayload struct {
		Package      string   `json:"package"`
		Capabilities []string `json:"capabilities"`
	}
	if err := json.Unmarshal(planOut, &planPayload); err != nil {
		t.Fatalf("plan output is not valid JSON: %v\nOutput:\n%s", err, string(planOut))
	}
	if planPayload.Package != "downloadsd" {
		t.Errorf("expected plan package downloadsd, got %q", planPayload.Package)
	}
}
